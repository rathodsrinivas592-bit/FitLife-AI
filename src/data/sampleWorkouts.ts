// Helper to pull exercises from the database safely with custom rep/set overrides if needed
const getEx = (id: string, customSets?: number, customReps?: string) => {
  const item = EXERCISE_DATABASE[id];
  if (!item) {
    return {
      id,
      name: id.replace(/-/g, ' ').replace(/\b\w/g, l => l.toUpperCase()),
      sets: customSets || 3,
      reps: customReps || '10 - 12 reps',
      restSeconds: 60,
      durationEstimate: '5 mins',
      instructions: 'Perform with controlled technique and full range of motion.',
      targetMuscle: 'Target Muscle',
      tips: 'Maintain proper breathing and control throughout.',
    };
  }
  return {
    ...item,
    sets: customSets || item.sets,
    reps: customReps || item.reps,
  };
};

